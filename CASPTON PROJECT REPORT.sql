---Task 4: International Sales Analysis

--Exclude all sales made within the United Kingdom.
SELECT *
FROM dbo.SALES
WHERE Country <> 'United Kingdom';

--Calculate the total revenue generated by each remaining country.
SELECT 
    Country,
    SUM(Quantity * UnitPrice) AS Total_Revenue
FROM dbo.SALES
WHERE Quantity > 0 
    AND Country <> 'United Kingdom'
GROUP BY Country
ORDER BY Total_Revenue DESC;

--Identify the country with the highest international sales revenue.
SELECT TOP 1
    Country,
    SUM(Quantity * UnitPrice) AS Total_Revenue
FROM dbo.SALES
WHERE Quantity > 0 
    AND Country <> 'United Kingdom'
GROUP BY Country
ORDER BY Total_Revenue DESC;

---Discuss possible reasons why this country performs well.
--1) Geographic and logistical proximity: Countries close to the UK (Netherlands, Ireland, France, Germany) benefit from shorter shipping times and lower freight costs compared to more distant markets — making it easier and cheaper for wholesale buyers there to order regularly and in bulk.
--2) Established trading relationships / EU market access: At the time this dataset was recorded (2010–2011), the UK was still in the EU, meaning trade with other EU countries faced fewer customs/logistics barriers than non-EU markets. This likely made countries like Netherlands or Germany naturally easier and cheaper to sell into than, say, Australia or the US.
--3) Currency and pricing dynamics: Exchange rate conditions during 2010–2011 could have made UK goods relatively cheap for buyers in certain countries — a macro factor outside the company's direct control, but useful context.

---Recommend strategies for expanding sales in other international markets.
--1) Identify "lookalike" markets based on the top performer's traits
--2) Localized promotional timing
--3) Test smaller markets with low-cost pilot campaigns
--4) Address logistics friction directly