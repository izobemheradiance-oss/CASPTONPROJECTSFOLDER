---Task 3: Customer Ordering Behaviour
--Extract the hour from each order's purchase time.
SELECT 
    InvoiceDate,
    DATEPART(HOUR, InvoiceDate) AS OrderHour
FROM dbo.SALES;

--Determine which hour of the day records the highest number of customer orders.
SELECT TOP 1
    DATEPART(HOUR, InvoiceDate) AS OrderHour,
    COUNT(DISTINCT InvoiceNo) AS NumberOfOrders
FROM dbo.SALES
GROUP BY DATEPART(HOUR, InvoiceDate)
ORDER BY NumberOfOrders DESC;

SELECT 
    DATEPART(HOUR, InvoiceDate) AS OrderHour,
    COUNT(DISTINCT InvoiceNo) AS NumberOfOrders
