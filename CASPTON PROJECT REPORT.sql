---Task 1: Sales Performance Analysis

--total sales revenue generated for each month.
SELECT 
    FORMAT(InvoiceDate, 'yyyy-MM') AS SalesMonth,
   SUM(Quantity * UnitPrice) AS Revenue
FROM dbo.SALES
GROUP BY FORMAT(InvoiceDate, 'yyyy-MM')
ORDER BY SalesMonth;

-- month with the highest total revenue and the month with the lowest total revenue.

--Highest revenue month:
SELECT TOP 1
    YEAR(InvoiceDate) AS SalesYear,
    MONTH(InvoiceDate) AS SalesMonth,
    SUM(Quantity * UnitPrice) AS Revenue
FROM dbo.SALES
GROUP BY YEAR(InvoiceDate), MONTH(InvoiceDate)
ORDER BY Revenue DESC;
--Lowest revenue month:
SELECT TOP 1
    YEAR(InvoiceDate) AS SalesYear,
    MONTH(InvoiceDate) AS SalesMonth,
    SUM(Quantity * UnitPrice) AS Revenue
FROM dbo.SALES
GROUP BY YEAR(InvoiceDate), MONTH(InvoiceDate)
ORDER BY Revenue ASC;

--possible reasons why these months performed differently.
--1) Holiday shopping cycle: November's peak lines up with pre-Christmas wholesale restocking; retailers buy well ahead of the season to have stock ready.
